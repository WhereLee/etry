-- ============================================================
-- 站内信 link 索引
--
-- 撤回提问时要按 link 把对应通知的跳转地址置空。
-- 没有索引时这条 UPDATE 只能全表扫描，而且 MySQL 在 RR 隔离级别下
-- 会把扫描到的所有行都锁住，期间任何人的站内信写入都会被挡住。
-- 这条路径是「学员撤回一个提问」，不该有这种代价。
-- ============================================================

ALTER TABLE t_message
    ADD KEY idx_msg_link (link);
